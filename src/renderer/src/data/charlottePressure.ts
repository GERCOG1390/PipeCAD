import { SizeId, n } from './sizes'

type Row<K extends string> = Record<K, number> & { pn?: string }

function table<K extends string>(cols: K[], rows: [SizeId, string, ...string[]][]): Partial<Record<SizeId, Row<K>>> {
  const out: Partial<Record<SizeId, Row<K>>> = {}
  for (const [size, pn, ...vals] of rows) {
    const r = { pn } as Row<K>
    cols.forEach((c, i) => ((r as Record<string, number>)[c] = n(vals[i])))
    out[size] = r
  }
  return out
}

function pairTable<K extends string>(cols: K[], rows: [SizeId, SizeId, string, ...string[]][]): Map<string, Row<K>> {
  const out = new Map<string, Row<K>>()
  for (const [a, b, pn, ...vals] of rows) {
    const r = { pn } as Row<K>
    cols.forEach((c, i) => ((r as Record<string, number>)[c] = n(vals[i])))
    out.set(`${a}|${b}`, r)
  }
  return out
}
export const pairKey = (a: SizeId, b: SizeId): string => `${a}|${b}`

